-- Authenticated users can upload only below their own UID prefix.
drop policy if exists "asset_owner_insert" on storage.objects;

create policy "asset_owner_insert"
on storage.objects for insert to authenticated
with check (
  bucket_id = 'menu-assets'
  and (storage.foldername(name))[1] = (select auth.uid())::text
);

-- Needed so Storage can return uploaded object metadata.
drop policy if exists "asset_owner_select" on storage.objects;

create policy "asset_owner_select"
on storage.objects for select to authenticated
using (
  bucket_id = 'menu-assets'
  and (
    owner_id = (select auth.uid())::text
    or (storage.foldername(name))[1] = (select auth.uid())::text
  )
);

drop policy if exists "asset_owner_update" on storage.objects;

create policy "asset_owner_update"
on storage.objects for update to authenticated
using (
  bucket_id = 'menu-assets'
  and owner_id = (select auth.uid())::text
)
with check (
  bucket_id = 'menu-assets'
  and (storage.foldername(name))[1] = (select auth.uid())::text
);

drop policy if exists "asset_owner_delete" on storage.objects;

create policy "asset_owner_delete"
on storage.objects for delete to authenticated
using (
  bucket_id = 'menu-assets'
  and owner_id = (select auth.uid())::text
);

